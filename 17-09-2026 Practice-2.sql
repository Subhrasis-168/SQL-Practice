-- Using patient, doctor, and medicine, display:
-- Patient name
-- Doctor name
-- City
-- Age
-- Medicine name
-- Medicine price
-- Conditions:
-- City is not Bangalore
-- Age is 20–70, but exclude 40–50
-- Medicine price is less than 250 OR greater than 1000
-- Exclude patients whose city is Delhi
-- Doctor and medicine must both match the patient
-- Sort by city ASC, medicine price DESC, age ASC
-- Skip 50
-- Return 35 records.

select p.patient_name, d.doctor_name , p.city,p.age,m.medicine_name,m.price
from patient as p 
inner join doctor as d 
on p.patient_id = d.patient_id
inner join medicine as m
on p.patient_id = m.patient_id
where p.city != "Bangalore"
and ((p.age between 20 and 70) and (p.age not between 40 and 50))
and (m.price < 250 or m.price > 1000)
and p.city != "Delhi"
order by p.city asc , m.price desc , p.age asc
limit 35 offset 50;

